# ── Routes and bodies ───────────────────────────────────────────────────────

#: v1's table plus one route. The verb of an existing route never changes.
ENDPOINTS_ADDED: Final = (("POST", "lease/renew", "agent"),)

#: `route -> {request, response}`: exact key sets and JSON types. `standing` is a
#: GET, so its request is the empty body. A key not listed is refused.
LEASE_BODIES: Final = {
    "lease/acquire": {
        "request": {"dispatch_run": "str", "ttl_seconds": "int"},
        "response": {"lease_id": "str", "ttl_seconds": "int"},
    },
    "lease/covers": {
        "request": {"lease_id": "str", "dispatch_run": "str"},
        "response": {"covers": "bool"},
    },
    "lease/renew": {
        "request": {"lease_id": "str", "dispatch_run": "str"},
        "response": {"lease_id": "str", "ttl_seconds": "int"},
    },
    "lease/release": {
        "request": {"lease_id": "str", "host_mutated": "bool"},
        "response": {"released": "bool", "replay": "bool"},
    },
    "lease/standing": {
        "request": {},
        "response": {"standing": "str"},
    },
}
STANDING_VALUES: Final = ("free", "held", "expired_unreleased")
RETRY_IDEMPOTENCY_ADDED: Final = {
    "lease/renew": "(lease_id, nonce): a retry carries a new nonce and is a new "
    "request; a renew never grants past lease_max_seconds",
}

#: Signed refusals of the lease routes, `code -> HTTP status`.
LEASE_ERRORS: Final = {
    "lease_not_held": 409,
    "lease_expired": 409,
    "lease_max_reached": 409,
    "lease_held": 409,
    "reconcile_marker_required": 409,
}

_TYPES: Final = {"str": str, "int": int, "bool": bool}


def check_lease_body(route: str, direction: str, body: object) -> None:
    """Exact keys, exact JSON types (a bool is never an int)."""
    spec = LEASE_BODIES.get(route)
    if spec is None or direction not in spec:
        raise TargetApiError(f"no {direction} body for {route!r}", "unknown_body")
    shape = spec[direction]
    if not isinstance(body, dict) or set(body) != set(shape):
        raise TargetApiError(
            f"{route} {direction} carries exactly {sorted(shape)}", "body_keys"
        )
    for key, kind in shape.items():
        value = body[key]
        expected = _TYPES[kind]
        if not isinstance(value, expected) or (
            expected is int and isinstance(value, bool)
        ):
            raise TargetApiError(f"{route} {direction}.{key} is {kind}", "body_type")
    if route in {"lease/acquire", "lease/renew"} and direction == "response":
        if body["ttl_seconds"] < 1:
            raise TargetApiError("a granted ttl is positive", "body_value")
    if route == "lease/standing" and direction == "response":
        if body["standing"] not in STANDING_VALUES:
            raise TargetApiError("unknown standing", "body_value")


# ── The reference lease ledger ──────────────────────────────────────────────


def renew_grant(*, ttl_seconds: int, lease_max_seconds: int, held_seconds: int) -> int:
    """`min(ttl, max - held)`; a spent maximum is `lease_max_reached`."""
    remaining = lease_max_seconds - held_seconds
    if remaining <= 0:
        raise TargetApiError("the lease maximum is spent", "lease_max_reached")
    return min(ttl_seconds, remaining)


@dataclass(slots=True)
class _Lease:
    lease_id: str
    dispatch_run: str
    acquired_at: datetime
    expires_at: datetime
    max_seconds: int
    ttl_seconds: int
    released: bool = False


class LeaseLedger:
    """What CP's lease endpoints must do, as a reference the vectors replay.

    One lease per host. Every call is given its own clock reading, so a replay is
    deterministic. The wire statuses are `LEASE_ERRORS`.
    """

    def __init__(self) -> None:
        self._lease: _Lease | None = None
        self._serial = 0

    def acquire(
        self,
        *,
        now: datetime,
        dispatch_run: str,
        ttl_seconds: int,
        lease_max_seconds: int,
        reconciled: bool,
    ) -> dict[str, object]:
        """A missing reconcile marker is refused BEFORE anything else."""
        if not reconciled:
            raise TargetApiError(
                "an expired, unreleased lease needs its reconcile marker",
                "reconcile_marker_required",
            )
        held = self._lease
        if held is not None and not held.released:
            if held.dispatch_run == dispatch_run:
                return {"lease_id": held.lease_id, "ttl_seconds": held.ttl_seconds}
            if now < held.expires_at:
                raise TargetApiError("another run holds the host", "lease_held")
        self._serial += 1
        lease = _Lease(
            lease_id=f"lease-{self._serial:04d}",
            dispatch_run=dispatch_run,
            acquired_at=now,
            expires_at=now + timedelta(seconds=min(ttl_seconds, lease_max_seconds)),
            max_seconds=lease_max_seconds,
            ttl_seconds=ttl_seconds,
        )
        self._lease = lease
        return {
            "lease_id": lease.lease_id,
            "ttl_seconds": min(ttl_seconds, lease_max_seconds),
        }

    def covers(
        self, *, now: datetime, lease_id: str, dispatch_run: str
    ) -> dict[str, object]:
        held = self._lease
        covers = (
            held is not None
            and not held.released
            and held.lease_id == lease_id
            and held.dispatch_run == dispatch_run
            and now < held.expires_at
        )
        return {"covers": bool(covers)}

    def renew(
        self, *, now: datetime, lease_id: str, dispatch_run: str
    ) -> dict[str, object]:
        held = self._lease
        if (
            held is None
            or held.released
            or held.lease_id != lease_id
            or held.dispatch_run != dispatch_run
        ):
            raise TargetApiError("no such lease is held by this run", "lease_not_held")
        if now >= held.expires_at:
            raise TargetApiError("the lease expired", "lease_expired")
        grant = renew_grant(
            ttl_seconds=held.ttl_seconds,
            lease_max_seconds=held.max_seconds,
            held_seconds=int((now - held.acquired_at).total_seconds()),
        )
        held.expires_at = now + timedelta(seconds=grant)
        return {"lease_id": held.lease_id, "ttl_seconds": grant}

    def release(self, *, lease_id: str, host_mutated: bool) -> dict[str, object]:
        held = self._lease
        if held is None or held.lease_id != lease_id:
            raise TargetApiError("no such lease", "lease_not_held")
        if held.released:
            return {"released": True, "replay": True}
        held.released = True
        return {"released": True, "replay": False}

    def standing(self, *, now: datetime) -> dict[str, object]:
        held = self._lease
        if held is None or held.released:
            return {"standing": "free"}
        if now >= held.expires_at:
            return {"standing": "expired_unreleased"}
        return {"standing": "held"}


# ── Observation kinds ───────────────────────────────────────────────────────

OBSERVATION_KINDS: Final = ("deploy", "reconcile", "job")
JOB_OPERATION: Final = "run_job"
DEPLOY_OPERATIONS: Final = ("deploy", "rollback")


def check_observation_kind(kind: object, operation: object) -> None:
    """Kind `job` is the observation of a `run_job` plan, and only of one; kind
    `deploy` of a deploy/rollback plan; `reconcile` settles an expired lease and
    names the dispatch it belonged to, of any executable operation."""
    if kind not in OBSERVATION_KINDS:
        raise TargetApiError("unknown observation kind", "observation_kind_unknown")
    executable = (*DEPLOY_OPERATIONS, JOB_OPERATION)
    if operation not in executable:
        raise TargetApiError(
            "the operation is not one an agent observes", "observation_kind_mismatch"
        )
    if kind == "job" and operation != JOB_OPERATION:
        raise TargetApiError(
            "observation kind and operation disagree", "observation_kind_mismatch"
        )
    if kind == "deploy" and operation not in DEPLOY_OPERATIONS:
        raise TargetApiError(
            "observation kind and operation disagree", "observation_kind_mismatch"
        )


# ── The plan binding ────────────────────────────────────────────────────────

MIN_LEASE_TTL: Final = 120
MAX_LEASE_TTL: Final = 900
MAX_LEASE_MAX: Final = 10800
LEASE_MARGIN: Final = 120
_DISPATCHED_KEYS: Final = frozenset(
    {
        "name",
        "role",
        "single_use",
        "materials",
        "params",
        "params_env_digest",
        "argv",
        "timeout_seconds",
        "window",
    }
)
_MATERIAL: Final = re.compile(r"[A-Z][A-Z0-9_]*")


def _bad(message: str, code: str) -> TargetApiError:
    return TargetApiError(message, code)


def check_deploy_binding(binding: Mapping[str, Any], *, operation: str) -> None:
    """The v2 rules for `plan_snapshot.deploy_binding`, by operation."""
    job = binding.get("dispatched_job")
    if (operation == JOB_OPERATION) != (job is not None):
        raise _bad(
            "dispatched_job is an object for run_job and null for every other "
            "operation",
            "dispatched_job_mismatch",
        )
    roles = binding.get("roles") or []
    job_role = None if job is None else job.get("role")
    if (roles or job_role) and not (
        binding.get("secrets_namespace") and binding.get("secrets_environment")
    ):
        raise _bad(
            "a binding with roles carries secrets_namespace and secrets_environment",
            "naming_required",
        )
    raw_ttl = binding.get("lease_ttl_seconds")
    raw_max = binding.get("lease_max_seconds")
    for value in (raw_ttl, raw_max):
        if isinstance(value, bool) or not isinstance(value, int):
            raise _bad("the lease values are integers", "lease_split")
    ttl, maximum = int(str(raw_ttl)), int(str(raw_max))
    if job is None:
        if (
            not MIN_LEASE_TTL <= ttl <= MAX_LEASE_TTL
            or not ttl <= maximum <= MAX_LEASE_MAX
        ):
            raise _bad(
                "a serving lease is ttl 120..900 per grant and max ttl..10800",
                "lease_split",
            )
        return
    if not isinstance(job, dict) or set(job) != _DISPATCHED_KEYS:
        raise _bad("dispatched_job carries exactly its nine keys", "job_shape")
    present = (
        job["role"] is not None,
        job["single_use"] is not None,
        job["window"] is not None,
    )
    if len(set(present)) != 1:
        raise _bad(
            "role, single_use and window are all null or all present", "job_shape"
        )
    if not (
        isinstance(job["argv"], list)
        and job["argv"]
        and all(isinstance(a, str) and a for a in job["argv"])
    ):
        raise _bad("argv is the full closed command line", "job_shape")
    params = job["params"]
    if not isinstance(params, dict) or not all(
        isinstance(k, str) and _MATERIAL.fullmatch(k) and isinstance(v, str)
        for k, v in params.items()
    ):
        raise _bad("params is keyed by MATERIAL name with string values", "job_params")
    if job["materials"] != sorted(job["materials"]):
        raise _bad("materials are sorted", "job_shape")
    if not is_canonical_digest(job["params_env_digest"]):
        raise _bad("params_env_digest is sha256:<64 hex>", "job_shape")
    timeout = job["timeout_seconds"]
    if isinstance(timeout, bool) or not isinstance(timeout, int) or timeout < 1:
        raise _bad("timeout_seconds is a positive integer", "job_shape")
    if ttl != timeout + LEASE_MARGIN or maximum != ttl:
        raise _bad("a job lease ttl and max are both timeout + 120", "lease_split")
    if roles:
        raise _bad("a job plan mints no serving role", "job_shape")
    images = binding.get("images") or []
    if not images or any(i.get("source") != "present" for i in images):
        raise _bad("a job plan runs the image already present", "job_image_source")


# ── Domain separation: a request message and an observation envelope ────────

#: The PoP key signs BOTH a target request and an agent observation envelope. The
#: byte domains are disjoint by construction: a request is LF-joined text whose
#: first line is `dotmac.target_request.v1`; an observation envelope is the
#: canonical JSON of a statement carrying its own schema string
#: (`dotmac.agent-observation/2`) and begins with `{`. Neither parses as the other.
REQUEST_FIELD_COUNT: Final = 8


def parse_request_message(message: bytes) -> dict[str, str]:
    """Parse the LF-joined signed text of a target request, or refuse it."""
    from dotmac_deployment_control.target_api import REQUEST_PURPOSE

    try:
        lines = message.decode("utf-8").split("\n")
    except (UnicodeDecodeError, AttributeError):
        raise TargetApiError(
            "a request message is UTF-8 text", "not_a_request"
        ) from None
    if len(lines) != REQUEST_FIELD_COUNT or lines[0] != REQUEST_PURPOSE:
        raise TargetApiError(
            f"a request message is {REQUEST_FIELD_COUNT} LF-joined lines starting "
            f"{REQUEST_PURPOSE!r}",
            "not_a_request",
        )
    keys = (
        "purpose",
        "method",
        "path",
        "body_sha256",
        "credential_id",
        "target_ref",
        "issued_at",
        "nonce",
    )
    return dict(zip(keys, lines, strict=True))
