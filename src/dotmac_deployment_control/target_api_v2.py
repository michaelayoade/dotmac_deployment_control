"""The target-API contract, v2: the job-plan, lease and observation additions.

v2 is a DELTA over `target_api` (v1): the wire envelope is unchanged (signed
request and response messages, headers, base path, nonce ledger, unpadded
base64url). What v2 adds is pinned by `contract/target_api_v2.json`, generated by
`tests/unit/target_api_v2_vectors.py` from the functions below, and conformed to
by CP 5c and the deploy agent:

* the plan binding: `jobs` (definitions), `dispatched_job` (the one job a
  `run_job` plan runs, params keyed by MATERIAL), `secrets_namespace` /
  `secrets_environment`, and the split lease (`lease_ttl_seconds` per grant,
  `lease_max_seconds` total);
* the observation kind `job` and its kind/operation agreement;
* the lease routes: `acquire`, `covers`, `renew` (new), `release`, `standing`,
  with a reference ledger whose behaviour the vectors replay.

Pure: no I/O, no clock of its own (every time is passed in).
"""

